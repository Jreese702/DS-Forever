    /** where a verdict came from (reported as "dungeon_source") */
    const val LISTED = "listed-content-key-match"
    const val CHANGED = "geometry-changed-content"
    const val UNKNOWN = "geometry-unknown-root"
    const val MISSING_KEY = "geometry-missing-content-key"

    class Verdict(val dungeon: Boolean?, val source: String)

    /** The listed verdict when [contentKey] (the root's live CASC content key, 32 lower-case hex) matches; otherwise
     *  dungeon = null and the geometric rule decides. */
    fun verdict(rootFid: Int, contentKey: String?): Verdict {
        val listed = DUNGEON[rootFid]?.let { true to it } ?: NOT_DUNGEON[rootFid]?.let { false to it }
            ?: return Verdict(null, UNKNOWN)
        if (contentKey == null || !contentKey.matches(Regex("[0-9a-f]{32}"))) return Verdict(null, MISSING_KEY)
        return if (contentKey == listed.second) Verdict(listed.first, LISTED) else Verdict(null, CHANGED)
    }

    val dungeonCount: Int get() = DUNGEON.size
    val knownCount: Int get() = DUNGEON.size + NOT_DUNGEON.size
